export function getPhotographer(slug: string) {
  return photographers.find((p) => p.slug === slug);
}

export function getPhoto(id: string) {
  return photos.find((p) => p.id === id);
}

export function getMission(id: string) {
  return missions.find((m) => m.id === id);
}

export function photosByPhotographer(slug: string) {
  return photos.filter((p) => p.photographerSlug === slug);
}

export function photosByCategory(category: Category) {
  return photos.filter((p) => p.category === category);
}

export function featuredPhotos() {
  return photos.filter((p) => p.featured);
}

export function photoOfTheDay() {
  return photos.find((p) => p.photoOfTheDay) ?? photos[0];
}

export function searchCatalog(q: string) {
  const needle = q.trim().toLowerCase();
  if (!needle) return { photos: [] as Photo[], photographers: [] as Photographer[] };
  return {
    photos: photos.filter((p) => {
      const author = getPhotographer(p.photographerSlug)?.name ?? "";
      return (
        p.title.toLowerCase().includes(needle) ||
        p.location.toLowerCase().includes(needle) ||
        p.category.toLowerCase().includes(needle) ||
        author.toLowerCase().includes(needle) ||
        p.camera.toLowerCase().includes(needle)
      );
    }),
    photographers: photographers.filter(
      (p) =>
        p.name.toLowerCase().includes(needle) ||
        p.city.toLowerCase().includes(needle) ||
        p.country.toLowerCase().includes(needle),
    ),
  };
}
